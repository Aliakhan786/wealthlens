"use client";

import { useMutation } from "@tanstack/react-query";
import { AnimatePresence, motion } from "framer-motion";
import { Sparkles } from "lucide-react";
import { useState } from "react";
import ReactMarkdown from "react-markdown";
import { post } from "@/lib/api";
import { Button, Segmented, Skeleton } from "./ui";

interface ExplainResponse { text: string; source: "llm" | "template"; cached: boolean }

export function Markdown({ children }: { children: string }) {
  return (
    <div className="prose-ai text-sm">
      <ReactMarkdown components={{ a: (p) => <a {...p} target="_blank" rel="noopener noreferrer" /> }}>{children}</ReactMarkdown>
    </div>
  );
}

export function ExplainPanel({ assetId }: { assetId: string }) {
  const [lang, setLang] = useState<"en" | "hi">("en");
  const m = useMutation({ mutationFn: (l: "en" | "hi") => post<ExplainResponse>("/ai/explain", { asset_id: assetId, lang: l }) });

  return (
    <div className="card relative overflow-hidden p-5">
      <div className="pointer-events-none absolute -left-20 -top-20 h-56 w-56 rounded-full bg-brand/10 blur-3xl" />
      <div className="relative flex flex-wrap items-center justify-between gap-3">
        <div className="flex items-center gap-2">
          <span className="grid h-8 w-8 place-items-center rounded-xl bg-gradient-to-br from-brand to-gold text-slate-900"><Sparkles className="h-4 w-4" /></span>
          <div>
            <p className="font-semibold">Explain this to me</p>
            <p className="text-xs text-subtle">AI explains the numbers on this page — it doesn&apos;t invent data or give advice.</p>
          </div>
        </div>
        <div className="flex items-center gap-2">
          <Segmented options={[{ value: "en", label: "English" }, { value: "hi", label: "हिंदी" }]} value={lang}
            onChange={(l) => { setLang(l); if (m.data) m.mutate(l); }} />
          <Button onClick={() => m.mutate(lang)} disabled={m.isPending}>{m.isPending ? "Thinking…" : m.data ? "Regenerate" : "Explain"}</Button>
        </div>
      </div>
      <AnimatePresence mode="wait">
        {m.isPending && (
          <motion.div key="l" initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }} className="mt-4 space-y-2">
            <Skeleton className="h-4 w-full" /><Skeleton className="h-4 w-11/12" /><Skeleton className="h-4 w-4/5" />
          </motion.div>
        )}
        {m.data && !m.isPending && (
          <motion.div key="d" initial={{ opacity: 0, y: 8 }} animate={{ opacity: 1, y: 0 }} className="relative mt-4">
            <Markdown>{m.data.text}</Markdown>
            <p className="mt-2 text-[10px] uppercase tracking-wider text-subtle">
              {m.data.source === "llm" ? "Generated by Claude from WealthLens data" : "Offline explanation (add an API key for AI)"}{m.data.cached ? " · cached" : ""}
            </p>
          </motion.div>
        )}
        {m.isError && <p className="mt-3 text-sm text-down">{(m.error as Error).message}</p>}
      </AnimatePresence>
    </div>
  );
}
